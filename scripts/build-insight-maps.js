/*
 * Builds src/data/insights/mapShapes.js — compact SVG path data for the maps
 * on the insight pages — from the GeoJSON outlines in the arcadea-reels repo
 * (the same files the videos use).
 *
 *   node scripts/build-insight-maps.js <path-to-arcadea-reels>
 *
 * Sources and attribution (shown on the pages):
 *   australia.geojson  — Natural Earth 1:50m admin-1, public domain
 *   gold-coast.geojson — ABS ASGS 2021 LGA 33430, CC BY 4.0
 *   Rail / G:link stops — OpenStreetMap contributors, ODbL (from the 003 scenes.json)
 */
import fs from 'fs';
import path from 'path';
import process from 'process';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const reelsDir = process.argv[2];
if (!reelsDir) {
    console.error('Usage: node scripts/build-insight-maps.js <path-to-arcadea-reels>');
    process.exit(1);
}

const readJson = (p) => JSON.parse(fs.readFileSync(path.join(reelsDir, p), 'utf8'));

/** Equirectangular projection fitted to a bounding box, scaled by cos(mid-latitude). */
function makeProjection([lonMin, latMin, lonMax, latMax], width, pad) {
    const k = Math.cos((((latMin + latMax) / 2) * Math.PI) / 180);
    const scale = (width - pad * 2) / ((lonMax - lonMin) * k);
    const height = Math.round((latMax - latMin) * scale + pad * 2);
    const project = ([lon, lat]) => [
        +((lon - lonMin) * k * scale + pad).toFixed(1),
        +((latMax - lat) * scale + pad).toFixed(1),
    ];
    return { project, width, height };
}

function bbox(features) {
    let b = [Infinity, Infinity, -Infinity, -Infinity];
    const visit = (c) => {
        if (typeof c[0] === 'number') {
            b = [Math.min(b[0], c[0]), Math.min(b[1], c[1]), Math.max(b[2], c[0]), Math.max(b[3], c[1])];
        } else c.forEach(visit);
    };
    features.forEach((f) => visit(f.geometry.coordinates));
    return b;
}

/** Ring → path, dropping points closer than `minDist` units to the last kept one. */
function ringPath(ring, project, minDist) {
    const pts = [];
    for (const c of ring) {
        const p = project(c);
        const last = pts[pts.length - 1];
        if (!last || Math.hypot(p[0] - last[0], p[1] - last[1]) >= minDist) pts.push(p);
    }
    if (pts.length < 3) return '';
    return `M${pts.map((p) => p.join(' ')).join('L')}Z`;
}

function featurePath(feature, project, minDist) {
    const { type, coordinates } = feature.geometry;
    const polys = type === 'Polygon' ? [coordinates] : coordinates;
    return polys.flatMap((poly) => poly.map((ring) => ringPath(ring, project, minDist))).join('');
}

/* ---------------- Australia (states) ---------------- */
const aus = readJson('public/maps/australia.geojson');
const ausProj = makeProjection(bbox(aus.features), 1000, 12);
const STATE_CODES = {
    'Western Australia': 'WA',
    'Northern Territory': 'NT',
    'South Australia': 'SA',
    Queensland: 'QLD',
    Tasmania: 'TAS',
    Victoria: 'VIC',
    'New South Wales': 'NSW',
};
const australia = {
    width: ausProj.width,
    height: ausProj.height,
    states: aus.features.map((f) => ({
        code: STATE_CODES[f.properties.name],
        name: f.properties.name,
        d: featurePath(f, ausProj.project, 2.2),
    })),
    // Label / arrow anchors (approximate state centres, plus capitals)
    points: Object.fromEntries(Object.entries({
        WA: [121.5, -26.0],
        NT: [133.4, -19.5],
        SA: [135.6, -30.0],
        QLD: [145.0, -22.5],
        NSW: [146.8, -32.2],
        VIC: [144.3, -37.0],
        TAS: [146.6, -42.0],
        ACT: [149.13, -35.28],
        Brisbane: [153.025, -27.47],
        Sydney: [151.21, -33.87],
    }).map(([k, v]) => [k, ausProj.project(v)])),
};

/* ---------------- Gold Coast ---------------- */
const gc = readJson('public/maps/gold-coast.geojson');
const scenes = readJson('videos/003-gold-coast-supply/scenes.json');
const mapScene = (scenes.scenes || scenes).find((s) => s.props?.visual?.kind === 'map');
const { routes, markers } = mapScene.props.visual;
const gcProj = makeProjection(bbox(gc.features), 600, 16);
const line = (pts) => pts.map((p) => gcProj.project([p.lon, p.lat]));
const goldCoast = {
    width: gcProj.width,
    height: gcProj.height,
    outline: gc.features.map((f) => featurePath(f, gcProj.project, 1.2)).join(''),
    rail: line(routes[0].points),
    lightRail: line(routes[1].points),
    markers: markers.map((m) => ({
        label: m.label,
        note: m.note,
        side: m.labelSide || 'right',
        at: gcProj.project([m.lon, m.lat]),
    })),
};

const out = `/* Generated by scripts/build-insight-maps.js — do not edit by hand. */

export const AUSTRALIA = ${JSON.stringify(australia)};

export const GOLD_COAST = ${JSON.stringify(goldCoast)};
`;
const outPath = path.join(__dirname, '..', 'src', 'data', 'insights', 'mapShapes.js');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${(out.length / 1024).toFixed(1)} KB)`);
